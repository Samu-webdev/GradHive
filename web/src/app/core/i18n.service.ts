@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly document = inject(DOCUMENT);
  private readonly title = inject(Title);
  readonly language = signal<AppLanguage>(this.initialLanguage());

  constructor() {
    this.applyLanguage(this.language());
  }

  setLanguage(language: AppLanguage): void {
    this.language.set(language);
    localStorage.setItem('gradhive-language', language);
    this.applyLanguage(language);
  }

  toggleLanguage(): void {
    this.setLanguage(this.language() === 'fr' ? 'en' : 'fr');
  }

  translate(value: string): string {
    if (this.language() !== 'en') return value;
    const count = /^(\d+) condition\(s\) à remplir$/.exec(value);
    if (count) return `${count[1]} requirement(s) not yet met`;
    const welcome = /^Bienvenue, (.+) !$/.exec(value);
    if (welcome) return `Welcome, ${welcome[1]}!`;
    return ENGLISH[value] ?? value;
  }

  private applyLanguage(language: AppLanguage): void {
    this.document.documentElement.lang = language;
    this.title.setTitle(language === 'en' ? 'GradHive | Global academic and professional network' : 'GradHive | Réseau académique et professionnel');
    const description = this.document.querySelector<HTMLMetaElement>('meta[name="description"]');
    if (description) {
      description.content = language === 'en'
        ? 'GradHive is a global network showcasing academic journeys and research projects, connecting graduates with study and research opportunities.'
        : 'GradHive est un réseau international pour valoriser les parcours et projets académiques, découvrir des opportunités et explorer les postes TA/RA.';
    }
  }

  private initialLanguage(): AppLanguage {
    const saved = localStorage.getItem('gradhive-language');
    if (saved === 'en' || saved === 'fr') return saved;
    return navigator.language.toLowerCase().startsWith('en') ? 'en' : 'fr';
  }
}
